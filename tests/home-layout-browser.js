async page => {
  const results = [];
  const check = (value, label) => { if (!value) throw new Error(label); results.push(label); };
  await page.waitForSelector('.home-layout-card');
  const order = () => page.locator('[data-layout-key]').evaluateAll(nodes => nodes.map(node => node.dataset.layoutKey));
  check((await order()).length === 6, 'six actual homepage blocks');
  await page.getByRole('button', { name: '下移今日状态', exact: true }).click();
  check((await order())[0] === 'shortcuts', 'button reorder');
  await page.getByRole('button', { name: '拖动今日状态，也可按上下方向键', exact: true }).press('ArrowUp');
  check((await order())[0] === 'status', 'keyboard reorder');
  const handle = page.locator('[data-layout-key="shortcuts"] .home-layout-handle');
  await handle.scrollIntoViewIfNeeded();
  const from = await handle.boundingBox();
  const target = await page.locator('[data-layout-key="status"]').boundingBox();
  await page.mouse.move(from.x + 20, from.y + 20);
  await page.mouse.down();
  await page.mouse.move(target.x + 80, Math.max(90, target.y + 35), { steps: 12 });
  await page.mouse.up();
  check((await order())[0] === 'shortcuts', 'pointer drag reorder');
  await page.getByRole('button', { name: '隐藏重要考试', exact: true }).click();
  check(await page.locator('[data-layout-key="exams"]').evaluate(node => node.classList.contains('is-hidden')), 'hide preview');
  await page.getByRole('button', { name: '保存布局', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.home-layout-feedback').textContent.includes('已存本机'));
  await page.evaluate(() => { location.hash = '#/home'; });
  await page.waitForSelector('[data-home-block="shortcuts"]');
  check(await page.locator('#view > [data-home-block]').first().getAttribute('data-home-block') === 'shortcuts', 'saved order used on home');
  check(await page.locator('[data-home-block="exams"]').isHidden(), 'hidden block absent on home');
  check(await page.locator('.ao-workbench').count() === 1, 'task workbench remains functional block');
  await page.reload();
  await page.waitForSelector('[data-home-block="shortcuts"]');
  check(await page.locator('#view > [data-home-block]').first().getAttribute('data-home-block') === 'shortcuts', 'layout survives reload');
  check(await page.locator('[data-home-block="exams"]').isHidden(), 'visibility survives reload');
  await page.evaluate(() => { location.hash = '#/ops?section=layout'; });
  await page.waitForSelector('.home-layout-editor');
  await page.getByRole('button', { name: '恢复默认', exact: true }).click();
  check((await order())[0] === 'status', 'restore defaults draft');
  await page.getByRole('button', { name: '撤销修改', exact: true }).click();
  check((await order())[0] === 'shortcuts', 'cancel restores saved layout');
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile has no horizontal overflow');
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce', contrast: 'more' });
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
  await page.screenshot({ path: 'output/playwright/home-layout-mobile.png', fullPage: true });
  return { passed: results.length, results };
}
