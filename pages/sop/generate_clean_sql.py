    f.write("BEGIN;\n")
    for item in items_data:
        clean_info = clean_text(item["info"])
        # Escape single quotes for SQL
        clean_info_sql = clean_info.replace("'", "''")
        title_sql = item["title"].replace("'", "''")
        f.write(f"UPDATE public.sop_items SET info = '{clean_info_sql}' WHERE title = '{title_sql}';\n")
    f.write("COMMIT;\n")
