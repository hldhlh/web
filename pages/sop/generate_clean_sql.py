def clean_text(text):
    # Remove #, ##, ###, #### identifiers
    text = re.sub(r'#{1,6}\s*', '', text)
    # Remove ** bold
    text = re.sub(r'\*\*', '', text)
    # Remove Slide X identifiers
    text = re.sub(r'Slide \d+', '', text)
    # Remove empty lines that exceed 2
    text = re.sub(r'\n{3,}', '\n\n', text)
    # Strip whitespace
    text = text.strip()
    return text

